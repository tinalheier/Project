
import numpy as np

def designMatrixA(dictionary, active_GNSS):

    # dict = {}

    for point, systems in dictionary.items():

        x_r, y_r, z_r = point

        satellites = []
        for key, value in systems.items():
            
            if active_GNSS:
                if not active_GNSS.get(key, False):
                    continue 
                
                if isinstance(value, list):
                    satellites.extend(value)

        satellites_len = len(satellites)
        
        if satellites_len < 4:
            dictionary[point]["PDOP"] = 0
            continue


        A = np.zeros((satellites_len, 4))
        A[:, 3] = -1

        for i, sat in enumerate(satellites):

            _, x_s, y_s, z_s, *_ = sat

            dx =  x_s - x_r
            dy =  y_s - y_r
            dz =  z_s - z_r

            r_vector = np.sqrt((dx**2) + (dy**2) + (dz**2))

            A[i, :3] = [-dx/r_vector, -dy/r_vector, -dz/r_vector]

        

        Q = np.linalg.inv(A.T @ A)


        PDOP = np.sqrt(Q[0][0]+Q[1][1]+Q[2][2])
        dictionary[point]["PDOP"] = PDOP

      #REGN UT GDOP også

        #TO LG
        
    return dictionary

